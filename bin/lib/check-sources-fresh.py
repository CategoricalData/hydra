#!/usr/bin/env python3
"""Source-freshness check for the dist/json tree (#672, finding F1).

Answers one question: does the tracked dist/json still correspond to the module
sources under packages/? sync.sh's #773 Haskell-free fast path skips Phase 1
(source -> dist/json), so it must only be taken when the answer is yes; otherwise a
source edit followed by a non-Haskell sync would silently leave dist/json stale.

Sources hashed (the inputs of Phase 1, which the fast path skips):
  - packages/*/src/{main,test}/hydra/**.hydra              (textual sources, #837)
  - packages/*/src/{main,test}/haskell/Hydra/Sources/**.hs (Haskell DSL sources)
  - packages/*/package.json                                 (textualSources, dependencies)
Host-native DSL sources (hydra-{java,jvm,python,scala}) are not covered: their JSON is
regenerated by the Phase 1.5 heal (own freshness gate) and the Phase 5 native drivers.

Freshness:
  - Warm tree: the current hash equals the stamp recorded by `--record` (sync.sh
    records it after Phase 1 completes, or is skipped as clean).
  - Cold tree (no stamp): no source path differs between the merge-base with
    origin/main and the working tree (including untracked files). CI's consistency
    gate guarantees the committed dist/json matches the sources on main, so an
    unmodified source set means the tracked dist/json is current.

Exit 0 if fresh, 1 if stale (reason on stderr), 2 on usage error.

Usage: check-sources-fresh.py <hydra-root> [--record]
"""
import hashlib
import subprocess
import sys
from pathlib import Path

STAMP_REL = "dist/json/build/sources-stamp.txt"


def hash_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(65536), b''):
            h.update(chunk)
    return h.hexdigest()


def source_paths(hydra_root: Path) -> list:
    """Every Phase 1 source file under packages/, sorted."""
    packages = hydra_root / "packages"
    paths = set()
    if not packages.is_dir():
        return []
    for pkg in packages.iterdir():
        if not pkg.is_dir():
            continue
        manifest = pkg / "package.json"
        if manifest.is_file():
            paths.add(manifest)
        for src_set in ("main", "test"):
            hydra_dir = pkg / "src" / src_set / "hydra"
            if hydra_dir.is_dir():
                paths.update(hydra_dir.rglob("*.hydra"))
            dsl_dir = pkg / "src" / src_set / "haskell" / "Hydra" / "Sources"
            if dsl_dir.is_dir():
                paths.update(dsl_dir.rglob("*.hs"))
    return sorted(p for p in paths if p.is_file())


def hash_sources(hydra_root: Path) -> str:
    h = hashlib.sha256()
    for p in source_paths(hydra_root):
        h.update(str(p.relative_to(hydra_root)).encode('utf-8'))
        h.update(b'\0')
        h.update(hash_file(p).encode('utf-8'))
        h.update(b'\n')
    return h.hexdigest()


def git(hydra_root: Path, *args) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(hydra_root), *args], capture_output=True, text=True)


def cold_tree_fresh(hydra_root: Path) -> bool:
    """No stamp: fresh iff the source set is unchanged since the merge-base with origin/main."""
    mb = git(hydra_root, "merge-base", "HEAD", "origin/main")
    if mb.returncode != 0:
        print("  sources-fresh: no stamp and no merge-base with origin/main; treating as stale",
              file=sys.stderr)
        return False
    base = mb.stdout.strip()
    rels = [str(p.relative_to(hydra_root)) for p in source_paths(hydra_root)]
    # Changed or deleted tracked sources since the merge-base (working tree included).
    diff = git(hydra_root, "diff", "--name-only", base, "--", "packages")
    if diff.returncode != 0:
        print("  sources-fresh: git diff failed; treating as stale", file=sys.stderr)
        return False
    relset = set(rels)
    # Filter by path shape rather than membership in source_paths, so a deleted source counts too.
    changed = [f for f in diff.stdout.split() if is_source_path(f)]
    untracked = git(hydra_root, "ls-files", "--others", "--exclude-standard", "--", "packages")
    changed += [f for f in untracked.stdout.split() if f in relset]
    if changed:
        print(f"  sources-fresh: no stamp; {len(changed)} source file(s) differ from "
              f"merge-base {base[:10]} (e.g. {changed[0]})", file=sys.stderr)
        return False
    return True


def is_source_path(rel: str) -> bool:
    parts = rel.split("/")
    if len(parts) < 3 or parts[0] != "packages":
        return False
    if len(parts) == 3 and parts[2] == "package.json":
        return True
    if rel.endswith(".hydra") and "/src/" in rel and "/hydra/" in rel:
        return True
    return rel.endswith(".hs") and "/haskell/Hydra/Sources/" in rel


def main() -> int:
    if len(sys.argv) < 2:
        print(f"Usage: {sys.argv[0]} <hydra-root> [--record]", file=sys.stderr)
        return 2
    hydra_root = Path(sys.argv[1]).resolve()
    stamp = hydra_root / STAMP_REL
    current = hash_sources(hydra_root)

    if "--record" in sys.argv[2:]:
        stamp.parent.mkdir(parents=True, exist_ok=True)
        stamp.write_text(current + "\n")
        return 0

    if stamp.is_file():
        if stamp.read_text().strip() == current:
            return 0
        print("  sources-fresh: module sources changed since dist/json was last regenerated",
              file=sys.stderr)
        return 1
    return 0 if cold_tree_fresh(hydra_root) else 1


if __name__ == "__main__":
    sys.exit(main())
