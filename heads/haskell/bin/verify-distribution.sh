#!/usr/bin/env bash
# Verify the per-package Hydra Haskell distributions COMPILE together, pinned
# inter-package deps and all (they depend on each other == <version>, not yet on
# Hackage).
#
# Because the dependents pin a not-yet-published hydra-kernel (and each other), we
# can't `stack build` them in isolation. Instead this stages the chosen package set
# and wires it into ONE multi-package stack project (local `packages:` entries), so
# the pinned inter-package deps resolve against the local staged copies. A clean
# `stack build` of that project proves the set compiles as published.
#
# This is verification only — it does NOT produce or upload sdists (see
# publish-hackage.sh). It is the Haskell analog of running each head's
# test-distribution.sh against the assembled dist.
#
# Usage:
#   verify-distribution.sh [--keep] [--full]
#     --keep  leave the staging/build dir in place for inspection.
#     --full  verify the COMPLETE Hackage-shaped publish set (every registered
#             package + the hydra umbrella, ~15 packages) instead of the default
#             lightweight smoke set. Slower; used by prepare-release.sh gate 13
#             before an actual Hackage publish. The default set still includes
#             hydra-build (#573's fix — it must never again go unexercised), just
#             not every OTHER coder package on every routine invocation.

set -euo pipefail

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
HYDRA_HASKELL_DIR="$( cd "$SCRIPT_DIR/.." && pwd )"
HYDRA_ROOT="$( cd "$HYDRA_HASKELL_DIR/../.." && pwd )"

KEEP=false
FULL=false
for arg in "$@"; do
    case "$arg" in
        --keep) KEEP=true ;;
        --full) FULL=true ;;
        *) echo "Unknown argument: $arg" >&2; exit 1 ;;
    esac
done

VERSION="$("$HYDRA_ROOT/bin/lib/hydra-packages.py" current-version)"

if [ "$FULL" = true ]; then
    # The full Hackage publish set (leaves first), DERIVED from the hydra.json
    # registry (mirrors publish-hackage.sh) plus the hand-written `hydra` umbrella
    # appended last — so this verification always covers exactly what
    # publish-hackage.sh will assemble and upload, with no separately-maintained
    # package list to fall out of sync (#573).
    read -ra _REGISTRY_TOPO < <("$HYDRA_ROOT/bin/lib/hydra-packages.py" topo \
        $("$HYDRA_ROOT/bin/lib/hydra-packages.py" list))
    if [ "${#_REGISTRY_TOPO[@]}" -eq 0 ]; then
        echo "ERROR: could not derive publish set from hydra.json registry" >&2
        exit 1
    fi
    PKGS=("${_REGISTRY_TOPO[@]}" hydra)
else
    # Lightweight default smoke set: kernel, hydra-build (#573 — must always be
    # exercised here), the Haskell coder, and the umbrella. Runs on every routine
    # invocation, so it stays small; --full covers the rest before a real publish.
    PKGS=(hydra-kernel hydra-build hydra-haskell hydra)
fi

WORK="$(mktemp -d -t hydra-verify-dist-XXXXXX)"
cleanup() { [ "$KEEP" = true ] || rm -rf "$WORK"; }
trap cleanup EXIT

echo "=== Verifying Hydra Haskell per-package distributions compile ==="
echo "  Work dir: $WORK"
echo ""

# Stage each package into $WORK/<pkg> (no sdist), reusing the assembler's
# --no-sdist mode but redirecting its temp staging into our controlled tree.
# The assembler stages into its own mktemp dir, so we capture and move it.
for pkg in "${PKGS[@]}"; do
    echo "--- staging $pkg ---"
    out="$("$SCRIPT_DIR/assemble-haskell-distribution.sh" "$pkg" --no-sdist 2>&1)"
    echo "$out" | grep -E 'staged'
    stage="$(echo "$out" | grep -oE '/[^ ]+hydra-sdist-'"$pkg"'-[^ ]+' | head -1)"
    if [ -z "$stage" ] || [ ! -d "$stage" ]; then
        echo "ERROR: could not locate staging dir for $pkg" >&2
        exit 1
    fi
    mkdir -p "$WORK/$pkg"
    cp -R "$stage"/. "$WORK/$pkg/"
    # Drop the per-package stack.yaml; the umbrella project below supplies one.
    rm -f "$WORK/$pkg/stack.yaml"
    rm -rf "$stage"
done
echo ""

# One multi-package stack project tying the local packages together so the
# `== <version>` inter-package pins resolve against the local staged copies. The
# `packages:` list is generated FROM the same $PKGS array staged above — not a
# second hardcoded list — so it can never drift from what was actually staged (#573).
{
    echo "# Generated by verify-distribution.sh — ephemeral verification project."
    echo "resolver: lts-24.7"
    echo "system-ghc: true"
    echo "install-ghc: false"
    echo "packages:"
    for pkg in "${PKGS[@]}"; do
        echo "  - $pkg"
    done
    echo "extra-deps: []"
} > "$WORK/stack.yaml"

echo "=== Building the ${PKGS[*]} set together (stack build) ==="
cd "$WORK"
export STACK_WORK_DIR="$WORK/.stack-work"
if stack build 2>&1 | tee "$WORK/verify-build.log"; then
    echo ""
    echo "=== OK: all ${#PKGS[@]} packages compile as published ==="
else
    echo ""
    echo "=== FAIL: publish set did not compile (see $WORK/verify-build.log) ===" >&2
    KEEP=true   # keep for debugging
    exit 1
fi
